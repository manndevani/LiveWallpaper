#!/bin/sh
# embed.sh - turns shaders/glsl/*.glsl into C string macros (builtin_shaders.h).
# usage: embed.sh <glsl dir> > builtin_shaders.h
# The shaders contain no backslashes or double quotes; awk only escapes them
# to be safe.
dir=$1
echo "/* Generated by embed.sh from shaders/glsl. Don't edit. */"
echo "#pragma once"
for name in prelude epilogue aurora dunes nightsky ripples glowgrid; do
    awk -v name="$name" -v bs='\\' -v q='"' '
        BEGIN { print "#define SRC_" toupper(name) " " bs }
        {
            sub(/\r$/, "")
            out = ""
            for (i = 1; i <= length($0); i++) {
                c = substr($0, i, 1)
                if (c == bs || c == q) out = out bs
                out = out c
            }
            print "    " q out bs "n" q " " bs
        }
        END { print "    " q q }
    ' "$dir/$name.glsl" || exit 1
done
